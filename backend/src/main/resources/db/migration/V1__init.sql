CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    display_name VARCHAR(80) NOT NULL,
    role VARCHAR(32) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_app_user_username UNIQUE (username)
);

CREATE TABLE lead_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name VARCHAR(200) NOT NULL,
    country VARCHAR(80) NOT NULL,
    contact_name VARCHAR(80) NOT NULL,
    stage VARCHAR(32) NOT NULL,
    product_interest VARCHAR(200),
    source VARCHAR(80),
    notes VARCHAR(2000),
    owner_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_lead_owner FOREIGN KEY (owner_id) REFERENCES app_user (id)
);

CREATE INDEX idx_lead_owner ON lead_record (owner_id);
CREATE INDEX idx_lead_updated ON lead_record (updated_at);

CREATE TABLE contact_vault (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id BIGINT NOT NULL,
    phone_cipher VARCHAR(2000),
    phone_iv VARCHAR(64),
    email_cipher VARCHAR(2000),
    email_iv VARCHAR(64),
    whatsapp_cipher VARCHAR(2000),
    whatsapp_iv VARCHAR(64),
    phone_hash VARCHAR(64),
    email_hash VARCHAR(64),
    whatsapp_hash VARCHAR(64),
    phone_masked VARCHAR(80),
    email_masked VARCHAR(160),
    whatsapp_masked VARCHAR(80),
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_vault_lead UNIQUE (lead_id),
    CONSTRAINT fk_vault_lead FOREIGN KEY (lead_id) REFERENCES lead_record (id)
);

CREATE INDEX idx_vault_phone_hash ON contact_vault (phone_hash);
CREATE INDEX idx_vault_email_hash ON contact_vault (email_hash);
CREATE INDEX idx_vault_whatsapp_hash ON contact_vault (whatsapp_hash);

CREATE TABLE unmask_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manager_id BIGINT NOT NULL,
    lead_id BIGINT NOT NULL,
    reason VARCHAR(200) NOT NULL,
    started_at TIMESTAMP NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    ended_at TIMESTAMP,
    status VARCHAR(16) NOT NULL,
    CONSTRAINT fk_unmask_manager FOREIGN KEY (manager_id) REFERENCES app_user (id),
    CONSTRAINT fk_unmask_lead FOREIGN KEY (lead_id) REFERENCES lead_record (id)
);

CREATE INDEX idx_unmask_lookup ON unmask_session (manager_id, lead_id, status);

CREATE TABLE audit_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT,
    actor_name VARCHAR(80) NOT NULL,
    actor_username VARCHAR(64) NOT NULL,
    action VARCHAR(40) NOT NULL,
    target_type VARCHAR(40) NOT NULL,
    target_id BIGINT,
    reason VARCHAR(200),
    metadata_json VARCHAR(2000),
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_audit_actor FOREIGN KEY (actor_id) REFERENCES app_user (id)
);

CREATE INDEX idx_audit_created ON audit_event (created_at);
